#!/usr/bin/env bash
# scripts/check-pr-text.sh: a pull request title or commit message with a tool
# trailer ("Co-Authored-By" naming a tool or bot, a "Generated with" line) or a
# title with an em or en dash fails, and the message points at CONTRIBUTING.md.
# shellcheck source=tests/lib/harness.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib/harness.sh"

CHECK="$ROOT/scripts/check-pr-text.sh"
EM=$'\xe2\x80\x94'
EN=$'\xe2\x80\x93'
ROBOT=$'🤖'
check() { set +e; OUT="$(cd "${CHECK_DIR:-$ROOT}" && bash "$CHECK" "$@" 2>&1)"; CODE=$?; set -e; }

assert_file "$CHECK" "(the script exists)"

check "Fix the port check for a stopped bench (#123)"
assert_eq 0 "$CODE" "(a plain title passes)"$'\n'"$OUT"

check "Fix the port check ${EM} for a stopped bench"
assert_eq 1 "$CODE" "(an em dash in the title fails)"
assert_contains "$OUT" "CONTRIBUTING.md" "(the message points at CONTRIBUTING.md)"
assert_contains "$OUT" "dash" "(the message says dash)"

check "Fix the port check ${EN} for a stopped bench"
assert_eq 1 "$CODE" "(an en dash in the title fails)"

# commit messages through git
REPO="$TMP_DIR/repo"
CHECK_DIR="$REPO"
mkdir -p "$REPO"
(
  cd "$REPO"
  git init -q -b main
  git config user.name T; git config user.email t@example.com
  git commit -q --allow-empty -m "Start"
  git checkout -q -b topic
  git commit -q --allow-empty -m "Add a thing" -m "Why it is needed ${EM} an em dash in a body is allowed here."
) >/dev/null
check "Add a thing (#1)" "main..topic"
assert_eq 0 "$CODE" "(a clean commit passes; a dash in a body is not checked)"$'\n'"$OUT"

commit_with() { # TRAILER: a commit on topic, checked, then dropped
  (cd "$REPO" && git commit -q --allow-empty -m "Add another" -m "Body." -m "$1") >/dev/null
  check "Add a thing (#1)" "main..topic"
  (cd "$REPO" && git reset -q --hard HEAD~1)
}
for trailer in \
  "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>" \
  "Co-Authored-By: Claude Sonnet 5.5 (1M context) <x@example.com>" \
  "Co-authored-by: Claude <x@example.com>" \
  "Co-authored-by: Copilot <copilot@github.com>" \
  "Co-authored-by: GitHub Copilot <x@example.com>" \
  "Co-Authored-By: ChatGPT <x@openai.com>" \
  "Co-authored-by: Codex <x@example.com>" \
  "Co-authored-by: Cursor Agent <cursoragent@cursor.com>" \
  "Co-authored-by: some-tool[bot] <1+some-tool[bot]@users.noreply.github.com>" \
  "Co-authored-by: Someone <12+tool[bot]@users.noreply.github.com>" \
  "Co-authored-by: Anyone <noreply@anthropic.com>" \
  "Generated with Claude Code" \
  "Generated by Claude Code" \
  "Made with Claude Code" \
  "Generated with [Claude Code](https://claude.com/claude-code)" \
  "$ROBOT Generated with [Claude Code](https://claude.com/claude-code)" \
  "$ROBOT Generated with something"; do
  commit_with "$trailer"
  assert_eq 1 "$CODE" "(a commit with '$trailer' fails)"$'\n'"$OUT"
  assert_contains "$OUT" "CONTRIBUTING.md" "(the message points at CONTRIBUTING.md)"
done

for ok in \
  "Co-authored-by: Sumanth Udupi <s@example.com>" \
  "Co-authored-by: Devin Smith <devin@x.com>" \
  "Co-authored-by: Claude Martin <c@x.fr>" \
  "Co-authored-by: Jane <jane@openai.com>" \
  "Co-authored-by: Gemini Rossi <g@x.it>" \
  "The files generated with the build script are not committed." \
  "Made with care."; do
  commit_with "$ok"
  assert_eq 0 "$CODE" "('$ok' passes)"$'\n'"$OUT"
done

# the pull request description
body() { PR_BODY="$1" check "Add a thing (#1)"; }
body "Adds a thing.

$ROBOT Generated with [Claude Code](https://claude.com/claude-code)"
assert_eq 1 "$CODE" "(a Generated with line in the body fails)"
assert_contains "$OUT" "description" "(the message says the description)"
body $'Adds a thing.\n\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n'
assert_eq 1 "$CODE" "(a tool Co-Authored-By in the body fails, CRLF too)"
body "Adds a thing, and a dash $EM in the body is not checked. Files generated with the build script."
assert_eq 0 "$CODE" "(a clean body passes)"$'\n'"$OUT"
body ""
assert_eq 0 "$CODE" "(an empty body passes)"$'\n'"$OUT"

# a title that carries a trailer
check "Add a thing
Co-Authored-By: Claude <noreply@anthropic.com>"
assert_eq 1 "$CODE" "(a trailer in the title text fails)"

check
assert_eq 2 "$CODE" "(no title is a usage error)"
check "x" "nosuch..range"
assert_eq 2 "$CODE" "(an unreadable range is an error, not a pass)"

printf 'test-pr-text: ok\n'
