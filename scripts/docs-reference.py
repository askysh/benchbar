#!/usr/bin/env python3
"""Generate the tables of the CLI reference from the code, and check them.

The commands, flags, environment variables and needs of every command are
in lib/frappe-local/commands.sh (`benchbar commands --json`); the MCP tools
are in lib/frappe-local/mcp.py. The pages in docs/reference/cli/ keep their
prose and examples by hand, and the tables between these marker comments
come from here:

    <!-- generated:cli-commands install adopt service -->
    ...
    <!-- /generated:cli-commands -->

    <!-- generated:mcp-tools -->
    ...
    <!-- /generated:mcp-tools -->

The words after `cli-commands` are the commands the page covers (a command
word takes its subcommands with it: `site` is `site list`, `site add` ...).

    python3 -I scripts/docs-reference.py --write    rewrite the tables
    python3 -I scripts/docs-reference.py --check    fail when a table differs,
                                                    a command has no page, or a
                                                    page documents a flag the CLI
                                                    does not have (tests/test-docs.sh)

Standard library only. Commands of a Lab are included: the labs are switched
on for the run, in a throwaway HOME, so the output does not depend on the
machine it runs on.
"""

import glob
import importlib.util
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLI_PAGES = os.path.join(ROOT, "docs", "reference", "cli")
AGENTS_GUIDE = os.path.join(ROOT, "docs", "guides", "agents.md")
MARK_CLI = re.compile(r"<!-- generated:cli-commands ([^>]*?) -->\n.*?<!-- /generated:cli-commands -->", re.S)
MARK_MCP = re.compile(r"<!-- generated:mcp-tools -->\n.*?<!-- /generated:mcp-tools -->", re.S)
NOTE = "<!-- Generated by scripts/docs-reference.py from the code. Edit the code, then run: python3 -I scripts/docs-reference.py --write -->"


def catalogue():
    """`benchbar commands --json` with every Lab on, in a throwaway HOME."""
    labs = []
    with open(os.path.join(ROOT, "lib", "frappe-local", "labs.sh"), encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("lab~"):
                labs.append(line.split("~")[1])
    with tempfile.TemporaryDirectory() as home:
        env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": home, "LC_ALL": "C",
               # BENCHBAR_LABS is a test seam, read only under FL_TESTING=1: the tables list every lab's commands
               "BENCHBAR_LABS": ",".join(labs), "FL_TESTING": "1", "BENCHBAR_NONINTERACTIVE": "1", "NO_COLOR": "1",
               # a lab is on only where its platforms say so: list every lab's commands whatever machine this runs on
               "FL_PLATFORM": "macos"}
        out = subprocess.run(["bash", os.path.join(ROOT, "benchbar"), "commands", "--json"], env=env, cwd=home,
                             stdout=subprocess.PIPE, stderr=subprocess.PIPE, universal_newlines=True, check=True).stdout
    return json.loads(out)


def mcp_tools():
    spec = importlib.util.spec_from_file_location("benchbar_mcp", os.path.join(ROOT, "lib", "frappe-local", "mcp.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.tool_list()["tools"]


def cell(text):
    """A table cell: the pipe and the angle brackets would break the markdown."""
    return (text or "").replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")


def code(text):
    return "`%s`" % text.replace("|", "\\|") if text else ""


def cli_block(cat, words):
    """The tables of every command whose first word is in `words`."""
    cmds = [c for c in cat["commands"] if c["name"].split()[0] in words]
    lab_of = {g["name"]: g["lab"] for g in cat.get("gated", [])}
    for entry in cat.get("commands", []):
        if entry.get("lab"):
            lab_of[entry["name"].split()[0]] = entry["lab"]
    out = [NOTE, "", "| Command | Terminal | `sudo` | Network | Changes things | JSON |", "|---|---|---|---|---|---|"]
    for c in cmds:
        label = code(c["usage"] if c["usage"].startswith("benchbar ") else "benchbar " + c["usage"])
        lab = c.get("lab") or lab_of.get(c["name"].split()[0])
        if lab:
            label += " (Lab %s)" % code(lab)
        yn = lambda v: "yes" if v else "no"
        out.append("| %s | %s | %s | %s | %s | %s |" % (label, yn(c["tty"]), yn(c["sudo"]), yn(c["network"]),
                                                       yn(c["mutating"]), c["json"]))
    out += ["", "Terminal: may ask a question on a terminal. `sudo`: may run `sudo`. Network: may reach the network.",
            "JSON: `document` is one JSON line, `stream` is JSON lines ending in a `done` line.", ""]
    flags = [(c["name"], f) for c in cmds for f in c["flags"]]
    if flags:
        out += ["| Command | Flag | Value | What it does |", "|---|---|---|---|"]
        for name, f in flags:
            out.append("| %s | %s | %s | %s |" % (code(name), code(f["name"]), code(f["value"]), cell(f["help"])))
        out.append("")
    env = [(c["name"], e) for c in cmds for e in c["env"]]
    if env:
        out += ["| Command | Environment variable | What it does |", "|---|---|---|"]
        for name, e in env:
            out.append("| %s | %s | %s |" % (code(name), code(e["name"]), cell(e["help"])))
        out.append("")
    return "\n".join(out).rstrip("\n")


def mcp_block(tools):
    names = set(t["name"] for t in tools)
    out = [NOTE, "", "| Tool | Kind | What it does | Arguments |", "|---|---|---|---|"]
    for t in tools:
        schema = t["inputSchema"]
        required = set(schema.get("required", []))
        args = ", ".join(code(k) + ("*" if k in required else "") for k in schema["properties"]) or "none"
        a = t["annotations"]
        if t["name"].endswith("_plan") and t["name"][:-5] in names:
            # a plan that runs git fetch writes .git/FETCH_HEAD: it is annotated as not read only
            kind = "plan (read only)" if a["readOnlyHint"] else "plan (git fetch)"
        elif a["readOnlyHint"]:
            kind = "read"
        else:
            kind = "acts"
        first = re.split(r"(?<=\.)\s", t["description"].strip(), maxsplit=1)[0]
        out.append("| %s | %s | %s | %s |" % (code(t["name"]), kind, cell(first), args))
    out += ["", "An argument marked `*` is required. `bench` (the bench's path, from `benchbar_list`) is optional on every tool "
            "that has it: without it the tool uses the default bench.", ""]
    return "\n".join(out).rstrip("\n")


def render(path, text, cat, tools):
    """The page text with every generated block rewritten, and the commands the page claims."""
    claimed = []

    def cli(m):
        words = m.group(1).split()
        claimed.extend(words)
        return "<!-- generated:cli-commands %s -->\n%s\n<!-- /generated:cli-commands -->" % (m.group(1), cli_block(cat, words))

    text = MARK_CLI.sub(cli, text)
    text = MARK_MCP.sub(lambda m: "<!-- generated:mcp-tools -->\n%s\n<!-- /generated:mcp-tools -->" % mcp_block(tools), text)
    return text, claimed


def catalogue_flags(cat):
    """Every flag the catalogue names: its flag records, and the usage, summary and help text of
    commands whose flags are written only in the usage line (`lock write [--lock PATH]`)."""
    text = json.dumps(cat)
    found = set(re.findall(r"(?<![\w-])(--?[a-zA-Z][-a-zA-Z]*)", text))
    # the short forms: -y for --yes, and -nN of logs written as -n50
    return found | {"--version"} | ({"-y"} if "--yes" in found else set()) | ({"-n"} if "-nN" in found else set())


def documented_flags(text):
    """The flags a hand written table of a page lists: rows that start with a flag."""
    return set(re.findall(r"`(-[-a-zA-Z]+)", "\n".join(l for l in text.splitlines() if l.startswith("| `-"))))


def main(argv):
    mode = argv[1] if len(argv) > 1 else "--check"
    if mode not in ("--check", "--write"):
        sys.stderr.write(__doc__)
        return 2
    cat, tools = catalogue(), mcp_tools()
    problems, claimed_by = [], {}
    known = catalogue_flags(cat)
    for page in sorted(glob.glob(os.path.join(CLI_PAGES, "*.md")) + [AGENTS_GUIDE]):
        rel = os.path.relpath(page, ROOT)
        with open(page, encoding="utf-8") as fh:
            old = fh.read()
        new, claimed = render(page, old, cat, tools)
        for w in claimed:
            claimed_by.setdefault(w, []).append(rel)
        if new != old:
            if mode == "--write":
                with open(page, "w", encoding="utf-8") as fh:
                    fh.write(new)
                print("rewrote " + rel)
            else:
                problems.append("%s: a generated table differs from the code; run: python3 -I scripts/docs-reference.py --write" % rel)
        for flag in sorted(documented_flags(new) - known):
            problems.append("%s documents %s, which no command or global option has (commands --json)" % (rel, flag))
    tops = []
    for c in cat["commands"]:
        w = c["name"].split()[0]
        if w not in tops:
            tops.append(w)
    for w in tops:
        pages = claimed_by.get(w, [])
        if not pages:
            problems.append("the command %s is on no page: add it to a <!-- generated:cli-commands ... --> marker in docs/reference/cli/" % w)
        elif len(pages) > 1:
            problems.append("the command %s is on more than one page: %s" % (w, ", ".join(pages)))
    for w in claimed_by:
        if w not in tops:
            problems.append("a page marker names %s, which is not a command (commands --json)" % w)
    if mode == "--check":
        # code to docs: every MCP tool is named in the agents guide and the mcp reference
        for rel in ("docs/guides/agents.md", "docs/reference/cli/mcp.md"):
            with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
                text = fh.read()
            for t in tools:
                if "`%s`" % t["name"] not in text:
                    problems.append("%s does not name the MCP tool %s" % (rel, t["name"]))
        # docs to code: a page that names a tool the server does not have (a tool that was renamed or never built).
        # Every page under docs/ and AGENTS.md; a heading anchor such as #...-and-benchbar_sudogui is not a tool name
        known = set(t["name"] for t in tools)
        pages = sorted(glob.glob(os.path.join(ROOT, "docs", "**", "*.md"), recursive=True)) + [os.path.join(ROOT, "AGENTS.md")]
        for page in pages:
            rel = os.path.relpath(page, ROOT).replace(os.sep, "/")
            with open(page, encoding="utf-8") as fh:
                for name in sorted(set(re.findall(r"(?<![\w#-])benchbar_[a-z][a-z_]*", fh.read()))):
                    if name not in known:
                        problems.append("%s names %s, which is not an MCP tool of the server" % (rel, name))
        for p in problems:
            sys.stderr.write(p + "\n")
        if problems:
            return 1
        print("docs-reference: ok")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
