#!/usr/bin/env bash
# check-pr-text.sh: the pull request text rules of CONTRIBUTING.md.
#
#   PR_BODY=... scripts/check-pr-text.sh TITLE [RANGE]
#
# Fails (exit 1) when
#   - TITLE has an em dash (U+2014) or an en dash (U+2013),
#   - TITLE, the body (the PR_BODY variable) or the message of a commit in
#     RANGE (a git range such as origin/next-release..HEAD) has a tool trailer:
#       * a Co-Authored-By line whose name is a tool ("Claude Opus 5.5",
#         "Cursor Agent", "GitHub Copilot": a tool name, then only product
#         words and version numbers) or ends in [bot], or whose address is a
#         known tool or bot address (noreply@anthropic.com, NAME[bot]@users.
#         noreply.github.com, ...). "Claude Martin" or "Devin Smith" is a
#         person and passes, and so does any name at openai.com;
#       * a "Generated with", "Generated by" or "Made with" line that names a
#         tool ("Generated with Claude Code"), or any such line that starts
#         with the robot emoji. "Files generated with the build script" passes.
# Dashes are checked in the title only. Exit 2 is a usage error or a range git
# cannot read, never a pass. Run by .github/workflows/pr-text.yml;
# tests/test-pr-text.sh tests it. Plain bash matching, no grep, so a tool error
# cannot read as "nothing found".
set -euo pipefail

[[ "$#" -ge 1 && "$#" -le 2 ]] || { printf 'usage: PR_BODY=... check-pr-text.sh TITLE [RANGE]\n' >&2; exit 2; }
title="$1"
range="${2:-}"
body="${PR_BODY:-}"

fail=0
problem() { printf 'PR text: %s\n' "$1" >&2; fail=1; }

em=$'\xe2\x80\x94'
en=$'\xe2\x80\x93'
case "$title" in
  *"$em"* | *"$en"*) problem "the title has an em dash or an en dash: use a colon, a comma or a new sentence" ;;
esac

tools='claude|anthropic|copilot|chatgpt|openai|codex|cursor|gemini|aider|devin|windsurf|codeium'
name_re="^(github )?($tools)( (code|opus|sonnet|haiku|agent|ai|bot|assistant|[0-9][0-9a-z.-]*))*\$"
email_re='^(noreply@anthropic\.com|noreply@openai\.com|copilot@github\.com|cursoragent@cursor\.com|.*\[bot\]@users\.noreply\.github\.com)$'
gen_re="(generated|made|created|written) (with|by) \[?(an? )?($tools|ai)([^a-z]|\$)"
gen_any_re='(generated|made) (with|by)'
co_re='^[[:space:]]*co-authored-by:[[:space:]]*(.*)$'
robot=$'\xf0\x9f\xa4\x96'

# tool_lines TEXT: the lines of TEXT that are a tool trailer, one per line
tool_lines() {
  local line low rest name email
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%$'\r'}"
    low="$(printf '%s' "$line" | tr '[:upper:]' '[:lower:]')"
    if [[ "$low" =~ $co_re ]]; then
      rest="${BASH_REMATCH[1]}"
      name="${rest%%<*}"; email=""
      [[ "$rest" == *"<"* ]] && { email="${rest#*<}"; email="${email%%>*}"; }
      name="$(printf '%s' "$name" | sed -e 's/([^)]*)//g' -e 's/[[:space:]][[:space:]]*/ /g' -e 's/^ //' -e 's/ $//')"
      if [[ "$name" =~ $name_re || "$name" == *"[bot]" || "$email" =~ $email_re ]]; then printf '%s\n' "$line"; fi
    elif [[ "$low" =~ $gen_re ]]; then
      printf '%s\n' "$line"
    elif [[ "$line" == *"$robot"* && "$low" =~ $gen_any_re ]]; then
      printf '%s\n' "$line"
    fi
  done <<<"$1"
}

scan() { # LABEL TEXT
  local l
  while IFS= read -r l; do
    [[ -n "$l" ]] && problem "$1 has a tool trailer: $l"
  done <<<"$(tool_lines "$2")"
  return 0
}

scan "the title" "$title"
scan "the description" "$body"

if [[ -n "$range" ]]; then
  # a range git cannot read is an error, never a pass
  shas="$(git log --format=%H --no-merges "$range")" || { printf 'check-pr-text: cannot read the range %s\n' "$range" >&2; exit 2; }
  for sha in $shas; do
    msg="$(git show -s --format=%B "$sha")" || { printf 'check-pr-text: cannot read commit %s\n' "$sha" >&2; exit 2; }
    scan "commit ${sha:0:8}" "$msg"
  done
fi

if [[ "$fail" == 1 ]]; then
  printf 'Rule: a plain imperative title that ends in the pull request number, no em or en dash in the title, no tool trailer (no Co-Authored-By for a tool, no "Generated with" line) in the title, the description or any commit; see "What a pull request needs" in CONTRIBUTING.md.\n' >&2
  printf 'Fix: edit the pull request title or description, and reword the commits (git rebase, then force push with lease).\n' >&2
  exit 1
fi
printf 'PR text: ok\n'
